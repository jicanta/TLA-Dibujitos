void _generateForLoop(FILE* outputFile, char *iterator, Array *array, Sentences *block) {
    if (!iterator || !array || !block) return;    

    SymbolEntry iteratorEntry = getSymbolEntry(currentCompilerState()->symbolTable, iterator);
    if (iteratorEntry.type == NULL_TYPE) {
        logError(_logger, "Loop variable '%s' not found in symbol table.", iterator);
        return;
    }

    switch (array->type) {
    case IDENTIFIER_ARRAY: {
        SymbolEntry arrayEntry = getSymbolEntryWithScope(currentCompilerState()->symbolTable, array->identifier, currentCompilerState()->scopesStack);
        if (arrayEntry.type != ARRAY_TYPE) {
            logError(_logger, "Identifier '%s' is not an array.", array->identifier);
            return;
        }
        for (int i = 0; i < arrayEntry.value.arrayData.size; i++) {
            switch (arrayEntry.value.arrayData.elements[i].type)
            {
            case INTEGER_TYPE:
                iteratorEntry.value.integerData = arrayEntry.value.arrayData.elements[i].value.integerData;
                break;
            case FLOAT_TYPE:
                iteratorEntry.value.floatData = arrayEntry.value.arrayData.elements[i].value.floatData;
                break;
            case VECTOR_TYPE:
                iteratorEntry.value.vectorData = arrayEntry.value.arrayData.elements[i].value.vectorData;
                break;
            default:
                break;
            }
            updateSymbol(currentCompilerState()->symbolTable, iteratorEntry);
            _generateSentences(outputFile, block);
        }
        break;
    }
    case BASIC_ARRAY: {
        Expressions *current = array->expressionList->expressions;
        while (current) {
            switch (typeOfExpression(current->expression))
            {
            case INTEGER_TYPE:
                iteratorEntry.value.integerData = _evaluateExpressionAsInt(current->expression);
                break;
            case FLOAT_TYPE:
                iteratorEntry.value.floatData = _evaluateExpressionAsFloat(current->expression);
                break;
            case VECTOR_TYPE:
                iteratorEntry.value.vectorData = _evaluateExpressionAsVector(current->expression);
                break;
            default:
                break;
            }
            updateSymbol(currentCompilerState()->symbolTable, iteratorEntry);
            _generateSentences(outputFile, block);
            current = current->next;
        }
        break;
    }
    case INTERVAL_ARRAY: {
        int start = _evaluateExpressionAsInt(array->leftExpression);
        int end = _evaluateExpressionAsInt(array->rightExpression);
        while(start <= end) {
            iteratorEntry.value.integerData = start;
            updateSymbol(currentCompilerState()->symbolTable, iteratorEntry);
            _generateSentences(outputFile, block);
            start++;
        }
        break;
    }
    
    default:
        break;
    }
}

void _generateArrayElementAssignment(char *arrayIdentifier, Expression *arrayIndexExpression, Expression *arrayElementExpression) {
    if (!arrayIdentifier || !arrayIndexExpression || !arrayElementExpression) return;
    
    SymbolEntry entry = getSymbolEntryWithScope(currentCompilerState()->symbolTable, arrayIdentifier, currentCompilerState()->scopesStack);
    if (entry.type == NULL_TYPE) {
        logError(_logger, "Array identifier '%s' not found in symbol table.", arrayIdentifier);
        return;
    }
    if (entry.type != ARRAY_TYPE) {
        logError(_logger, "Identifier '%s' is not an array.", arrayIdentifier);
        return;
    }
    
    int index = _evaluateExpressionAsInt(arrayIndexExpression);
    if (index < 0 || index >= entry.value.arrayData.size) {
        logError(_logger, "Index %d out of bounds for array '%s'.", index, arrayIdentifier);
        return; // TODO error
    }
    
    switch (entry.value.arrayData.elements[index].type) {
    case INTEGER_TYPE:
        entry.value.arrayData.elements[index].value.integerData = _evaluateExpressionAsInt(arrayElementExpression);
        break;
    case FLOAT_TYPE:
        entry.value.arrayData.elements[index].value.floatData = _evaluateExpressionAsFloat(arrayElementExpression);
        break;
    case VECTOR_TYPE:
        entry.value.arrayData.elements[index].value.vectorData = _evaluateExpressionAsVector(arrayElementExpression);
        break;
    default:
        logError(_logger, "Cannot assign to array '%s' of type %s.", arrayIdentifier, symbolTypeToString(entry.type));
        return;
    }
        
    updateSymbol(currentCompilerState()->symbolTable, entry);
}
/**
 * Generates a sentence
 */
static void _generateSentence(FILE* outputFile, Sentence * sentence) {
    if (!sentence) return;
    
    switch (sentence->type) {
        case FUNCTION_SENTENCE:
            _generateFunctionCall(outputFile, sentence->functionIdentifier, sentence->functionArguments);
            break;
        case LOG_SENTENCE:
            _generateLog(outputFile, sentence->logString);
            break;
        case IMPORT_SENTENCE:
            _generateImport(outputFile, sentence->importPath);
            break;
        case ASSIGN_SENTENCE:
            _generateAssignment(sentence->assignIdentifier, sentence->assignExpression);
            break;
        case ASSIGN_ARRAY_SENTENCE:
            _generateArrayAssignment(sentence->assignArrayIdentifier, sentence->assignArray);
            break;
        case ASSIGN_ARRAY_ELEMENT_SENTENCE:
            _generateArrayElementAssignment(sentence->assignArrayElemIdentifier, sentence->assignArrayIndexExpression, sentence->assignArrayElementExpression);
            break;
        case IF_SENTENCE:
            if (_evaluateExpressionAsBool(sentence->ifBoolExpression)) {
                _generateSentences(outputFile, sentence->ifBlock->sentences);
            }
            break;
        case IF_ELSE_SENTENCE:
            if (_evaluateExpressionAsBool(sentence->ifBoolExpression)) {
                _generateSentences(outputFile, sentence->leftIfElseBlock->sentences);
            }
            else {
                _generateSentences(outputFile, sentence->rightIfElseBlock->sentences);
            }
            break;
        case FOR_SENTENCE:
            _generateForLoop(outputFile, sentence->forIdentifier, sentence->forArray, sentence->forBlock->sentences);
            break;
    }
}

/**
 * Generates sentences recursively
 */
static void _generateSentences(FILE* outputFile, Sentences * sentences) {
    if (!sentences) return;
    
    _generateSentences(outputFile, sentences->sentences);
    _generateSentence(outputFile, sentences->sentence);
}

/**
 * Generates the entire program
 */
static void _generateProgram(FILE* outputFile, Program * program) {
    if (!program) return;
    
    _generateSentences(outputFile, program->sentences);
}

