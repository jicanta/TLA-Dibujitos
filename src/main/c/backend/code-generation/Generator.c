/**
 * Evaluates an expression and returns its float value
 */
static float _evaluateExpressionAsFloat(Expression * expression) {
    if (!expression) return 0.0f;
    
    switch (expression->type) {
        case FACTOR:
            switch (expression->factor->type) {
                case INTEGER_FACTOR:
                    return (float)expression->factor->integerExpression;
                case DECIMAL_FACTOR:
                    return expression->factor->floatExpression;
                case IDENTIFIER_FACTOR: {
                    SymbolEntry entry = getSymbolEntry(currentCompilerState()->symbolTable, expression->factor->identifier);
                    if (entry.type == FLOAT_TYPE) {
                        return entry.value.floatData;
                    } else if (entry.type == INTEGER_TYPE) {
                        return (float)entry.value.integerData;
                    }
                    return 0.0f;
                }
                default:
                    return 0.0f;
            }
        case ADDITION:
            return _evaluateExpressionAsFloat(expression->leftExpression) + _evaluateExpressionAsFloat(expression->rightExpression);
        case SUBTRACTION:
            return _evaluateExpressionAsFloat(expression->leftExpression) - _evaluateExpressionAsFloat(expression->rightExpression);
        case MULTIPLICATION:
            return _evaluateExpressionAsFloat(expression->leftExpression) * _evaluateExpressionAsFloat(expression->rightExpression);
        case DIVISION: {
            float right = _evaluateExpressionAsFloat(expression->rightExpression);
            if (right != 0.0f) {
                return _evaluateExpressionAsFloat(expression->leftExpression) / right;
            }
            return 0.0f;
        }
        case GET_X: {
            VectorData vec = _evaluateExpressionAsVector(expression->expression);
            return vec.x;
        }
        case GET_Y: {
            VectorData vec = _evaluateExpressionAsVector(expression->expression);
            return vec.y;
        }
        case FUNCTION_EXPRESSION:
            if (strcmp(expression->functionIdentifier, "sqrt") == 0) {
                if (expression->functionArguments && expression->functionArguments->expressions) {
                    float arg = _evaluateExpressionAsFloat(expression->functionArguments->expressions->expression);
                    return sqrtf(arg);
                }
            }
            return 0.0f;
        default:
            return 0.0f;
    }
}

/**
 * Evaluates an expression and returns its integer value
 */
static int _evaluateExpressionAsInt(Expression * expression) {
    return (int)_evaluateExpressionAsFloat(expression);
}

/**
 * Evaluates an expression and returns its vector value
 */
static VectorData _evaluateExpressionAsVector(Expression * expression) {
    VectorData result = {0.0f, 0.0f};
    
    if (!expression) return result;
    
    switch (expression->type) {
        case FACTOR:
            if (expression->factor->type == VECTOR_FACTOR) {
                result.x = _evaluateExpressionAsFloat(expression->factor->vector->x);
                result.y = _evaluateExpressionAsFloat(expression->factor->vector->y);
            } else if (expression->factor->type == IDENTIFIER_FACTOR) {
                SymbolEntry entry = getSymbolEntry(currentCompilerState()->symbolTable, expression->factor->identifier);
                if (entry.type == VECTOR_TYPE) {
                    result = entry.value.vectorData;
                }
            }
            break;
        case ADDITION:
            {
                VectorData left = _evaluateExpressionAsVector(expression->leftExpression);
                VectorData right = _evaluateExpressionAsVector(expression->rightExpression);
                result.x = left.x + right.x;
                result.y = left.y + right.y;
            }
            break;
        case SUBTRACTION:
            {
                VectorData left = _evaluateExpressionAsVector(expression->leftExpression);
                VectorData right = _evaluateExpressionAsVector(expression->rightExpression);
                result.x = left.x - right.x;
                result.y = left.y - right.y;
            }
            break;
        case MULTIPLICATION:
            {
                VectorData left = _evaluateExpressionAsVector(expression->leftExpression);
                VectorData right = _evaluateExpressionAsVector(expression->rightExpression);
                // Assuming multiplication is component-wise
                result.x = left.x * right.x;
                result.y = left.y * right.y;
            }
            break;
        default:
            break; // TODO ERROR    
    }
    
    return result;
}

/**
 * Generates a circle element
 */
static void _generateCircle(FILE* outputFile, ExpressionList * arguments) {
    if (!arguments || !arguments->expressions) return;
    
    // First argument should be position (vector)
    VectorData position = _evaluateExpressionAsVector(arguments->expressions->expression);
    
    // Second argument should be radius (float)
    float radius = 50.0f; // default
    if (arguments->expressions->next) {
        radius = _evaluateExpressionAsFloat(arguments->expressions->next->expression);
    }
    
    // Convert to SVG coordinates (center the drawing)
    float svgX = _centerX + position.x;
    float svgY = _centerY - position.y; // Flip Y axis
    
    char* fillColor = _colorToHex(_svgContext.fillColor);
    char* strokeColor = _colorToHex(_svgContext.strokeColor);
    
    fprintf(outputFile, "  <circle cx=\"%.2f\" cy=\"%.2f\" r=\"%.2f\" fill=\"%s\" stroke=\"%s\" stroke-width=\"%d\" class=\"%s-layer\"/>\n",
            svgX, svgY, radius, fillColor, strokeColor, _svgContext.strokeWidth,
            _svgContext.layer == 1 ? "front" : "back");
    
    free(fillColor);
    free(strokeColor);
}

/**
 * Generates a curve (Bezier path)
 */
static void _generateCurve(FILE* outputFile, ExpressionList * arguments) {
    if (!arguments || !arguments->expressions) return;
    
    Expressions* expr = arguments->expressions;
    if (!expr || !expr->next || !expr->next->next || !expr->next->next->next) return;
    
    VectorData p1 = _evaluateExpressionAsVector(expr->expression);
    VectorData cp1 = _evaluateExpressionAsVector(expr->next->expression);
    VectorData cp2 = _evaluateExpressionAsVector(expr->next->next->expression);
    VectorData p2 = _evaluateExpressionAsVector(expr->next->next->next->expression);
    
    // Convert to SVG coordinates
    float x1 = _centerX + p1.x;
    float y1 = _centerY - p1.y;
    float cx1 = _centerX + cp1.x;
    float cy1 = _centerY - cp1.y;
    float cx2 = _centerX + cp2.x;
    float cy2 = _centerY - cp2.y;
    float x2 = _centerX + p2.x;
    float y2 = _centerY - p2.y;
    
    char* fillColor = _colorToHex(_svgContext.fillColor);
    char* strokeColor = _colorToHex(_svgContext.strokeColor);
    
    fprintf(outputFile, "  <path d=\"M %.2f %.2f C %.2f %.2f %.2f %.2f %.2f %.2f\" fill=\"%s\" stroke=\"%s\" stroke-width=\"%d\" class=\"%s-layer\"/>\n",
            x1, y1, cx1, cy1, cx2, cy2, x2, y2, fillColor, strokeColor, _svgContext.strokeWidth,
            _svgContext.layer == 1 ? "front" : "back");
    
    free(fillColor);
    free(strokeColor);
}

