void generate(CompilerState * compilerState) {
    logDebugging(_logger, "Generating SVG output...");
    
    FILE* outputFile = stdout; // Output to stdout
    
    _generateSVGHeader(outputFile);
    _generateProgram(outputFile, compilerState->abstractSyntaxtTree);
    _generateSVGFooter(outputFile);
    
    logDebugging(_logger, "SVG generation is done.");
}

void generateToFile(CompilerState * compilerState, const char * outputPath) {
    logDebugging(_logger, "Generating SVG output to file: %s", outputPath);
    
    FILE* outputFile = fopen(outputPath, "w");
    if (outputFile == NULL) {
        logError(_logger, "Failed to open output file: %s", outputPath);
        return;
    }
    
    _generateSVGHeader(outputFile);
    _generateProgram(outputFile, compilerState->abstractSyntaxtTree);
    _generateSVGFooter(outputFile);
    
    if (fclose(outputFile) != 0) {
        logError(_logger, "Failed to close output file: %s", outputPath);
    }
    
    logDebugging(_logger, "SVG generation to file is done.");
}
